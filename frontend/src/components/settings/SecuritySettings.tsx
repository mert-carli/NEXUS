import { useState } from 'react'
import { useSettingsStore } from '@/store/settingsStore'
import { SettingSection, SettingRow, ToggleSwitch, SaveStatus, StatusBadge } from './SettingsUI'
import { Shield, Lock } from 'lucide-react'

export function SecuritySettings() {
  const { backendSettings, updateSetting } = useSettingsStore()
  const [saveState, setSaveState] = useState<{ isSaving: boolean; isSuccess: boolean; error: string | null }>({
    isSaving: false,
    isSuccess: false,
    error: null,
  })

  const handleUpdate = async (key: string, value: any) => {
    setSaveState({ isSaving: true, isSuccess: false, error: null })
    try {
      await updateSetting(key, value)
      setSaveState({ isSaving: false, isSuccess: true, error: null })
      setTimeout(() => setSaveState((prev) => ({ ...prev, isSuccess: false })), 2000)
    } catch (err: any) {
      setSaveState({ isSaving: false, isSuccess: false, error: err.message })
    }
  }

  if (!backendSettings) return null
  const security = backendSettings.security || {}
  const execution = backendSettings.execution || {}

  return (
    <div className="space-y-6 max-w-4xl">
      <div className="flex justify-between items-center mb-6">
        <div>
          <h2 className="text-xl font-semibold text-[#F3F4F6]">Security Center</h2>
          <p className="text-[#8B949E] text-xs mt-1">Local-first security controls strictly enforced by the backend engine.</p>
        </div>
        <SaveStatus {...saveState} />
      </div>

      {/* Security Status Card */}
      <div className="bg-[#0D1117] border border-[#202832] rounded-xl mb-6 p-6">
        <div className="flex items-center gap-4 mb-6">
          <div className="h-12 w-12 rounded-lg bg-[#202832] flex items-center justify-center shrink-0">
            <Shield className="h-6 w-6 text-[#18A957]" />
          </div>
          <div>
            <div className="flex items-center gap-2 mb-1">
              <h3 className="text-[#F3F4F6] font-medium uppercase tracking-wider text-xs">NEXUS SECURITY</h3>
              <StatusBadge status="protected" label="Protected" />
            </div>
            <p className="text-[#8B949E] text-xs">Local-first security controls are enforced by the backend.</p>
          </div>
        </div>

        <div className="grid grid-cols-2 md:grid-cols-4 gap-4 pt-4 border-t border-[#202832]">
          <div>
            <div className="text-[10px] text-[#8B949E] uppercase tracking-wider mb-1">Path Sandbox</div>
            <div className="text-xs text-[#18A957] font-mono flex items-center gap-1">
              <Lock className="w-3 h-3" /> Protected
            </div>
          </div>
          <div>
            <div className="text-[10px] text-[#8B949E] uppercase tracking-wider mb-1">Hash Validation</div>
            <div className="text-xs text-[#18A957] font-mono flex items-center gap-1">
              <Lock className="w-3 h-3" /> Protected
            </div>
          </div>
          <div>
            <div className="text-[10px] text-[#8B949E] uppercase tracking-wider mb-1">AI Approval</div>
            <div className="text-xs text-[#18A957] font-mono flex items-center gap-1">
              <Lock className="w-3 h-3" /> Protected
            </div>
          </div>
          <div>
            <div className="text-[10px] text-[#8B949E] uppercase tracking-wider mb-1">Command Policy</div>
            <div className="text-xs text-amber-400 font-mono capitalize">
              {execution.EXECUTION_POLICY || 'Strict'}
            </div>
          </div>
        </div>
      </div>

      <SettingSection title="Enforced Protections" description="Mandatory security policies enforced by security_validator.py">
        <SettingRow
          title="Path Sandbox"
          description="AI modifications cannot escape the project root directory. Always Enabled."
          isCritical={true}
        >
          <ToggleSwitch
            checked={true}
            disabled={true}
            disabledReason="Security Critical: Path sandboxing cannot be disabled."
            onChange={() => {}}
          />
        </SettingRow>
        <SettingRow
          title="File Hash Validation"
          description="SHA256 file hashes are verified before applying AI modifications to prevent race condition overwrites."
          isCritical={true}
        >
          <ToggleSwitch
            checked={true}
            disabled={true}
            disabledReason="Security Critical: Hash validation cannot be disabled."
            onChange={() => {}}
          />
        </SettingRow>
        <SettingRow
          title="Modification Approval"
          description="All code changes generated by the AI require explicit human review and acceptance before disk write."
          isCritical={true}
        >
          <ToggleSwitch
            checked={true}
            disabled={true}
            disabledReason="Security Critical: User approval requirement cannot be disabled."
            onChange={() => {}}
          />
        </SettingRow>
      </SettingSection>

      <SettingSection title="Scanners" description="Static code vulnerability and credential detection">
        <SettingRow
          title="Secret Detection"
          description="Scan project files for accidentally committed API keys, tokens, and credentials."
        >
          <ToggleSwitch
            checked={security.SCAN_FOR_SECRETS ?? true}
            onChange={(val: any) => handleUpdate('SCAN_FOR_SECRETS', val)}
          />
        </SettingRow>
        <div className="p-5 flex items-center justify-between bg-[#11161D]/50 border-t border-[#202832]">
          <div className="text-xs text-[#8B949E]">
            Automated security scanner for secret scanning across all workspace files.
          </div>
          <button
            disabled
            title="Security scanner module will be available in future phases"
            className="px-3 py-1.5 bg-[#202832] text-[#8B949E] text-xs font-medium rounded-md cursor-not-allowed opacity-60"
          >
            Run Security Scan (Not available in current version)
          </button>
        </div>
      </SettingSection>
    </div>
  )
}
